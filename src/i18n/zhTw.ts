const ZH_TW_CACHE = new Map<string, string>();

export function toZhTW(input: string): string {
  if (!input) return input;
  const cached = ZH_TW_CACHE.get(input);
  if (cached !== undefined) return cached;

  let result = input;
  for (const [from, to] of ZH_TW_PHRASES) {
    if (result.includes(from)) {
      result = result.split(from).join(to);
    }
  }

  let out = "";
  for (let i = 0; i < result.length; i++) {
    const ch = result[i];
    out += ZH_TW_CHAR_MAP[ch] ?? ch;
  }

  if (ZH_TW_CACHE.size < 2000) {
    ZH_TW_CACHE.set(input, out);
  }
  return out;
}
